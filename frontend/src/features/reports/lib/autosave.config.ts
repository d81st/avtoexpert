/**
 * Конфигурация автосохранения мастера заключения.
 *
 * Единственный источник истины для интервала автосохранения и множества
 * шагов, на которых автосохранение активно. Любой другой модуль кодовой
 * базы НЕ ДОЛЖЕН объявлять числовое значение задержки автосохранения
 * (AC 3.2 — единый источник истины).
 *
 * @see Requirement 3 в .kiro/specs/frontend-ux-enhancements/requirements.md
 */

/**
 * Задержка автосохранения мастера заключения, миллисекунды.
 *
 * Применяется в `useReportAutosave` для шагов wizard'а из
 * {@link AUTOSAVE_ELIGIBLE_STEPS}. Значение по умолчанию — 60_000 мс
 * (AC 3.1).
 *
 * Допустимый диапазон: [1000, 600000] миллисекунд включительно
 * (от 1 секунды до 10 минут). Значения вне диапазона нарушают контракт
 * AC 3.1 и не должны использоваться.
 *
 * ВАЖНО: это единственное место в кодовой базе, где объявлено числовое
 * значение интервала автосохранения (AC 3.2).
 */
export const AUTOSAVE_INTERVAL_MS = 60_000;

/**
 * Шаги мастера заключения, на которых выполняется автосохранение (AC 3.4).
 *
 * На шагах вне этого множества (например, шаг 1 или шаг 5) хук
 * `useReportAutosave` не планирует таймеров и отменяет любой ранее
 * запланированный таймер при входе в недопустимое состояние.
 */
export const AUTOSAVE_ELIGIBLE_STEPS = [2, 3, 4] as const;

/** Тип элемента множества {@link AUTOSAVE_ELIGIBLE_STEPS}. */
export type AutosaveEligibleStep = (typeof AUTOSAVE_ELIGIBLE_STEPS)[number];
